import { LandProject, LandParcel, LandLine, LandMarker, GeoPoint } from '../types';
import { calculateGeodesicArea, calculatePerimeter, calculateSegmentLengths } from './geoMath';

/**
 * Downloads a string or blob as a file in the browser
 */
export function downloadFile(content: string | Blob, filename: string, mimeType: string) {
  const blob = content instanceof Blob ? content : new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/**
 * Exports project as standard GIS GeoJSON FeatureCollection
 */
export function exportToGeoJSON(project: LandProject): string {
  const features = [
    // Parcels as Polygons
    ...project.parcels.map((p) => ({
      type: 'Feature',
      id: p.id,
      properties: {
        featureType: 'parcel',
        name: p.name,
        category: p.category,
        areaSqMeters: p.areaSqMeters,
        perimeterMeters: p.perimeterMeters,
        color: p.color,
        strokeColor: p.strokeColor,
        fillOpacity: p.fillOpacity,
        strokeWidth: p.strokeWidth,
        notes: p.notes || '',
        zoningCode: p.zoningCode || '',
        taxLotNumber: p.taxLotNumber || '',
        setbackMeters: p.setbackMeters || 0,
      },
      geometry: {
        type: 'Polygon',
        // In GeoJSON, polygon coordinates are [lng, lat] and closed (first == last)
        coordinates: [
          [
            ...p.coordinates.map((pt) => [Number(pt.lng.toFixed(7)), Number(pt.lat.toFixed(7))]),
            [Number(p.coordinates[0].lng.toFixed(7)), Number(p.coordinates[0].lat.toFixed(7))],
          ],
        ],
      },
    })),
    // Lines as LineStrings
    ...project.lines.map((l) => ({
      type: 'Feature',
      id: l.id,
      properties: {
        featureType: 'line',
        name: l.name,
        lineType: l.type,
        color: l.color,
        strokeWidth: l.strokeWidth,
        lengthMeters: l.lengthMeters,
        notes: l.notes || '',
      },
      geometry: {
        type: 'LineString',
        coordinates: l.coordinates.map((pt) => [
          Number(pt.lng.toFixed(7)),
          Number(pt.lat.toFixed(7)),
        ]),
      },
    })),
    // Markers as Points
    ...project.markers.map((m) => ({
      type: 'Feature',
      id: m.id,
      properties: {
        featureType: 'marker',
        name: m.name,
        markerCategory: m.category,
        notes: m.notes || '',
        elevationMeters: m.elevationMeters || 0,
      },
      geometry: {
        type: 'Point',
        coordinates: [Number(m.point.lng.toFixed(7)), Number(m.point.lat.toFixed(7))],
      },
    })),
  ];

  const geoJson = {
    type: 'FeatureCollection',
    metadata: {
      generator: 'GeoMark Satellite Studio',
      projectName: project.name,
      owner: project.clientOrOwner || '',
      location: project.locationName || '',
      exportedAt: new Date().toISOString(),
    },
    features,
  };

  return JSON.stringify(geoJson, null, 2);
}

/**
 * Exports project as Google Earth KML
 */
export function exportToKML(project: LandProject): string {
  const sanitize = (str: string) =>
    (str || '')
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;');

  // Convert hex color #RRGGBB to KML color aabbggrr
  const hexToKmlColor = (hex: string, alphaHex = '7f') => {
    const clean = hex.replace('#', '');
    if (clean.length === 6) {
      const r = clean.substring(0, 2);
      const g = clean.substring(2, 4);
      const b = clean.substring(4, 6);
      return `${alphaHex}${b}${g}${r}`;
    }
    return `${alphaHex}ffffff`;
  };

  let kml = `<?xml version="1.0" encoding="UTF-8"?>
<kml xmlns="http://www.opengis.net/kml/2.2">
  <Document>
    <name>${sanitize(project.name)}</name>
    <description>${sanitize(project.description || 'Land marking layout generated by GeoMark Satellite Studio')}</description>
`;

  // Parcel styles & placemarks
  project.parcels.forEach((p) => {
    const styleId = `style_${p.id}`;
    const polyColor = hexToKmlColor(p.color, Math.round((p.fillOpacity || 0.4) * 255).toString(16).padStart(2, '0'));
    const lineColor = hexToKmlColor(p.strokeColor || p.color, 'ff');

    const coordsStr = [
      ...p.coordinates.map((c) => `${c.lng.toFixed(7)},${c.lat.toFixed(7)},0`),
      `${p.coordinates[0].lng.toFixed(7)},${p.coordinates[0].lat.toFixed(7)},0`,
    ].join(' ');

    const acres = (p.areaSqMeters / 4046.856).toFixed(2);
    const hectares = (p.areaSqMeters / 10000).toFixed(2);

    kml += `
    <Style id="${styleId}">
      <LineStyle>
        <color>${lineColor}</color>
        <width>${p.strokeWidth || 2}</width>
      </LineStyle>
      <PolyStyle>
        <color>${polyColor}</color>
        <fill>1</fill>
        <outline>1</outline>
      </PolyStyle>
    </Style>
    <Placemark>
      <name>${sanitize(p.name)}</name>
      <description><![CDATA[
        <b>Zone:</b> ${sanitize(p.category)}<br/>
        <b>Area:</b> ${acres} Acres (${hectares} Hectares / ${Math.round(p.areaSqMeters).toLocaleString()} m²)<br/>
        <b>Perimeter:</b> ${Math.round(p.perimeterMeters).toLocaleString()} m<br/>
        ${p.zoningCode ? `<b>Zoning:</b> ${sanitize(p.zoningCode)}<br/>` : ''}
        ${p.notes ? `<b>Notes:</b> ${sanitize(p.notes)}<br/>` : ''}
      ]]></description>
      <styleUrl>#${styleId}</styleUrl>
      <Polygon>
        <extrude>1</extrude>
        <altitudeMode>clampToGround</altitudeMode>
        <outerBoundaryIs>
          <LinearRing>
            <coordinates>${coordsStr}</coordinates>
          </LinearRing>
        </outerBoundaryIs>
      </Polygon>
    </Placemark>`;
  });

  // Lines
  project.lines.forEach((l) => {
    const styleId = `style_line_${l.id}`;
    const lineColor = hexToKmlColor(l.color, 'ff');
    const coordsStr = l.coordinates.map((c) => `${c.lng.toFixed(7)},${c.lat.toFixed(7)},0`).join(' ');

    kml += `
    <Style id="${styleId}">
      <LineStyle>
        <color>${lineColor}</color>
        <width>${l.strokeWidth || 3}</width>
      </LineStyle>
    </Style>
    <Placemark>
      <name>${sanitize(l.name)}</name>
      <description><![CDATA[
        <b>Type:</b> ${sanitize(l.type)}<br/>
        <b>Length:</b> ${Math.round(l.lengthMeters).toLocaleString()} m (${(l.lengthMeters * 3.28084).toFixed(0)} ft)<br/>
        ${l.notes ? `<b>Notes:</b> ${sanitize(l.notes)}<br/>` : ''}
      ]]></description>
      <styleUrl>#${styleId}</styleUrl>
      <LineString>
        <tessellate>1</tessellate>
        <coordinates>${coordsStr}</coordinates>
      </LineString>
    </Placemark>`;
  });

  // Markers
  project.markers.forEach((m) => {
    kml += `
    <Placemark>
      <name>${sanitize(m.name)}</name>
      <description><![CDATA[
        <b>Category:</b> ${sanitize(m.category)}<br/>
        ${m.elevationMeters ? `<b>Elevation:</b> ${m.elevationMeters} m<br/>` : ''}
        ${m.notes ? `<b>Notes:</b> ${sanitize(m.notes)}<br/>` : ''}
      ]]></description>
      <Point>
        <coordinates>${m.point.lng.toFixed(7)},${m.point.lat.toFixed(7)},0</coordinates>
      </Point>
    </Placemark>`;
  });

  kml += `
  </Document>
</kml>`;

  return kml;
}

/**
 * Generates tabular CSV survey report for boundary analysis
 */
export function exportParcelSurveyCSV(parcel: LandParcel, projectName: string): string {
  const segments = calculateSegmentLengths(parcel.coordinates);
  let csv = `Project,${projectName}\n`;
  csv += `Parcel Name,${parcel.name}\n`;
  csv += `Category,${parcel.category}\n`;
  csv += `Area (Acres),${(parcel.areaSqMeters / 4046.856).toFixed(4)}\n`;
  csv += `Area (Hectares),${(parcel.areaSqMeters / 10000).toFixed(4)}\n`;
  csv += `Area (Sq Meters),${parcel.areaSqMeters.toFixed(2)}\n`;
  csv += `Perimeter (Meters),${parcel.perimeterMeters.toFixed(2)}\n\n`;

  csv += `Vertex #,Latitude,Longitude,Segment To,Distance (Meters),Distance (Feet),Bearing (Deg)\n`;

  parcel.coordinates.forEach((pt, idx) => {
    const seg = segments[idx];
    const distMeters = seg ? seg.distanceMeters.toFixed(2) : '0';
    const distFeet = seg ? (seg.distanceMeters * 3.28084).toFixed(2) : '0';
    const bearingStr = seg ? `${seg.bearingDeg.toFixed(1)}°` : '-';
    const toVertex = seg ? `#${seg.toIndex}` : '-';

    csv += `${idx + 1},${pt.lat.toFixed(7)},${pt.lng.toFixed(7)},${toVertex},${distMeters},${distFeet},${bearingStr}\n`;
  });

  return csv;
}

/**
 * Imports GeoJSON string and converts into LandProject data
 */
export function importGeoJSONToProject(geoJsonStr: string, currentProject: LandProject): LandProject {
  try {
    const data = JSON.parse(geoJsonStr);
    const features = data.features || (data.type === 'Feature' ? [data] : []);

    const newParcels: LandParcel[] = [...currentProject.parcels];
    const newLines: LandLine[] = [...currentProject.lines];
    const newMarkers: LandMarker[] = [...currentProject.markers];

    for (const f of features) {
      const geom = f.geometry;
      const props = f.properties || {};

      if (!geom) continue;

      if (geom.type === 'Polygon' && geom.coordinates?.[0]?.length >= 3) {
        const ring = geom.coordinates[0];
        const coords: GeoPoint[] = ring.slice(0, -1).map((pt: number[]) => ({
          lat: pt[1],
          lng: pt[0],
        }));

        const area = calculateGeodesicArea(coords);
        const perim = calculatePerimeter(coords);

        newParcels.push({
          id: `parcel_${Date.now()}_${Math.random().toString(36).substring(2, 6)}`,
          name: props.name || `Imported Parcel ${newParcels.length + 1}`,
          category: props.category || 'custom',
          color: props.color || '#0284c7',
          strokeColor: props.strokeColor || '#0369a1',
          fillOpacity: props.fillOpacity || 0.35,
          strokeWidth: props.strokeWidth || 2,
          coordinates: coords,
          areaSqMeters: area,
          perimeterMeters: perim,
          notes: props.notes || '',
          zoningCode: props.zoningCode || '',
        });
      } else if (geom.type === 'LineString' && geom.coordinates?.length >= 2) {
        const coords: GeoPoint[] = geom.coordinates.map((pt: number[]) => ({
          lat: pt[1],
          lng: pt[0],
        }));
        const len = calculatePerimeter(coords, false);

        newLines.push({
          id: `line_${Date.now()}_${Math.random().toString(36).substring(2, 6)}`,
          name: props.name || `Imported Line ${newLines.length + 1}`,
          type: props.lineType || 'fence',
          color: props.color || '#f59e0b',
          strokeWidth: props.strokeWidth || 3,
          coordinates: coords,
          lengthMeters: len,
          notes: props.notes || '',
        });
      } else if (geom.type === 'Point' && geom.coordinates?.length >= 2) {
        newMarkers.push({
          id: `marker_${Date.now()}_${Math.random().toString(36).substring(2, 6)}`,
          name: props.name || `Imported Point ${newMarkers.length + 1}`,
          category: props.markerCategory || 'survey_pin',
          point: { lat: geom.coordinates[1], lng: geom.coordinates[0] },
          notes: props.notes || '',
        });
      }
    }

    return {
      ...currentProject,
      parcels: newParcels,
      lines: newLines,
      markers: newMarkers,
      updatedAt: new Date().toISOString(),
    };
  } catch (err) {
    throw new Error('Invalid GeoJSON file structure');
  }
}
